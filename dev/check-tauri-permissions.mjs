/* dev/check-tauri-permissions.mjs — 防「命令注册了但没权限」回归
 *
 * 症状：前端 invoke 被 Tauri 权限层静默拒绝 → 工具栏不增高 → 菜单/面板被裁掉，
 * 肉眼只看到「点击没反应」，很难定位。
 *
 * 做法：抓 main.rs 的 invoke_handler 列表 + capabilities/default.json 的权限集合，
 * 校验每个已注册命令都能被某个 permission 覆盖：
 *   - `allow-<cmd 短横线化>` 出现在 capabilities 里（如 set_toolbar_expanded → allow-set-toolbar-expanded）
 *   - 或某个 permissions/*.toml 的 commands.allow 里显式列出了它
 *   - core:* / plugin:* 前缀的命令不走这条校验（由插件自身 default 权限覆盖）
 */
import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const ann = resolve(root, 'app/annota');

let pass = 0, fail = 0;
const failures = [];
const ok = (c, label, extra) => {
  if (c) { pass++; console.log(`# PASS ${label}`); }
  else { fail++; failures.push(`${label}${extra ? ' — ' + extra : ''}`); console.log(`# FAIL ${label}${extra ? ' — ' + extra : ''}`); }
};

// ---------- 抓 invoke_handler ----------
const mainRs = readFileSync(resolve(ann, 'src/main.rs'), 'utf8');
const handlerMatch = mainRs.match(/generate_handler!\[([\s\S]*?)\]/);
if (!handlerMatch) {
  console.error('# FAIL 未能从 main.rs 抓到 generate_handler![]');
  process.exit(1);
}
const commands = handlerMatch[1]
  .split(',')
  .map((s) => String(s).trim())
  .filter((s) => s && !s.startsWith('//'));
console.log(`# 抓到 ${commands.length} 个已注册命令`);

// ---------- 抓 capabilities 权限 ----------
const caps = JSON.parse(readFileSync(resolve(ann, 'capabilities/default.json'), 'utf8'));
const capsPerms = new Set(caps.permissions || []);

const permDir = resolve(ann, 'permissions');

// 解析 permissions/*.toml 里所有 [[permission]] 块：identifier → commands.allow
// （一个文件可能有多个块，且 identifier 不是每个文件只有一个）
function parsePermissionBlocks(txt) {
  const out = [];
  const re = /\[\[permission\]\]([\s\S]*?)(?=\n\[\[permission\]\]|\s*$)/g;
  let m;
  while ((m = re.exec(txt)) !== null) {
    const body = m[1];
    const idm = body.match(/identifier\s*=\s*"([^"]+)"/);
    const am = body.match(/commands\.allow\s*=\s*\[([\s\S]*?)\]/);
    if (!idm) continue;
    const cmds = am
      ? am[1].split(',').map((s) => String(s).trim().replace(/^["']|["']$/g, '')).filter(Boolean)
      : [];
    out.push({ id: idm[1], cmds });
  }
  return out;
}

const permBlocks = [];
for (const f of readdirSync(permDir)) {
  if (!f.endsWith('.toml')) continue;
  const txt = readFileSync(resolve(permDir, f), 'utf8');
  for (const b of parsePermissionBlocks(txt)) permBlocks.push({ file: f, ...b });
}
// 统计口径统一走 parsePermissionBlocks（真实解析器）——不再另写一份正则，
// 避免「日志里说覆盖 N 个、断言里其实是另一套」这种漂移。
const coveredCmdCount = new Set(permBlocks.flatMap((b) => b.cmds)).size;
console.log(`# capabilities 权限 ${capsPerms.size} 条 · ${permBlocks.length} 个 permission 块覆盖 ${coveredCmdCount} 个命令`);

// ---------- 校验 ----------
// Tauri 的真实规则：toml 里定义了 permission，capabilities 里还必须显式引用它，
// 两者缺一不可。只查「被某个 toml 覆盖」会漏报（这正是本检查器初版的 bug）。
const missing = [];
for (const cmd of commands) {
  const kebab = cmd.replace(/_/g, '-');
  // 该命令最终可由哪些 permission identifier 承载
  const candidates = [`allow-${kebab}`, `allow-${cmd}`];
  for (const b of permBlocks) {
    if (b.cmds.includes(cmd)) candidates.push(b.id);
  }
  // autogenerated 目录下每个文件对应一个 allow-<name>
  for (const f of readdirSync(resolve(permDir, 'autogenerated'))) {
    if (f === `${cmd}.toml`) candidates.push(`allow-${f.replace(/\.toml$/, '')}`);
  }
  const covered = candidates.some((id) => capsPerms.has(id));
  if (!covered) missing.push(`${cmd}（候选：${[...new Set(candidates)].join(' | ')}，均未被 capabilities 引用）`);
}
ok(missing.length === 0, '每个已注册命令都有权限覆盖', missing.join('; '));

// ---------- 反向：capabilities 里 allow-* 指向的 permission 标识符必须真实存在 ----------
// 注意：这里绝不能把 capsPerms 自己塞进 knownIds —— 那样 knownIds 会包含所有被检查项，
// `dangling` 永远是空数组、检查永远 PASS，等于静默废掉这条断言（OCR 审查抓到的正是这个）。
const knownIds = new Set(permBlocks.map((b) => b.id));
// build.rs 自动生成的：文件名是 snake_case（capture_frame.toml），identifier 是 kebab-case（allow-capture-frame）
for (const f of readdirSync(resolve(permDir, 'autogenerated'))) {
  knownIds.add(`allow-${f.replace(/\.toml$/, '').replace(/_/g, '-')}`);
}
// core:* / plugin:* 由 tauri 内置提供，不参与悬空判定（其清单不在本仓库）
const dangling = [...capsPerms].filter(
  (p) => p.startsWith('allow-') && !knownIds.has(p)
);
ok(dangling.length === 0, 'capabilities 里无悬空 allow-* 权限', dangling.join(', '));

// 自检：把已知不存在的标识符喂进去，断言检查器确实能报出来（防止再次退化成恒真）
{
  const fake = new Set([...capsPerms, 'allow-definitely-not-a-real-permission']);
  const caught = [...fake].filter((p) => p.startsWith('allow-') && !knownIds.has(p));
  ok(caught.length === 1 && caught[0] === 'allow-definitely-not-a-real-permission',
    '自检：悬空检查能检出伪造的权限标识符（防止恒真断言）', caught.join(','));
}

console.log(`\n# RESULT ${fail === 0 ? 'PASS' : 'FAIL'} (${pass}/${pass + fail})`);
if (failures.length) { console.log('# 失败项:'); failures.forEach((f) => console.log('  - ' + f)); }
process.exit(fail === 0 ? 0 : 1);